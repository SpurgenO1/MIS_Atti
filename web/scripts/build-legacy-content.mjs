import fs from "fs"
import path from "path"
import { fileURLToPath, pathToFileURL } from "url"
import { parse } from "node-html-parser"

const __dirname = path.dirname(fileURLToPath(import.meta.url))

/** Flipbook-style pages need scripts; ship full HTML for iframe srcDoc */
const FULL_DOCUMENT_FILES = new Set(["AnnualReport23.html", "YI Health report.html"])

/** Only used by extract-portfolio.mjs — not bundled for the app */
const SKIP_FILES = new Set(["Initiatives.html"])

function escapeRegExp(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")
}

function buildEventRouteByFile(portfolioItems, extraEventPages) {
  const m = new Map()
  for (const p of portfolioItems) m.set(p.file, `/events/${p.slug}`)
  for (const p of extraEventPages) m.set(p.file, `/events/${p.slug}`)
  return m
}

function rewriteLinks(html, portfolioItems, extraEventPages, htmlFileToRoute) {
  let s = html
  const eventPaths = buildEventRouteByFile(portfolioItems, extraEventPages)
  eventPaths.forEach((route, file) => {
    const re = new RegExp(`href=(["'])${escapeRegExp(file)}([^"']*?)\\1`, "gi")
    s = s.replace(re, `href=$1${route}$2$1`)
  })
  Object.entries(htmlFileToRoute).forEach(([file, route]) => {
    const re = new RegExp(`href=(["'])${escapeRegExp(file)}([^"']*?)\\1`, "gi")
    s = s.replace(re, `href=$1${route}$2$1`)
  })
  s = s.replace(/\b(src|href)=(["'])(\.\.\/)*assets\//gi, "$1=$2/assets/")
  s = s.replace(/\baction=(["'])email\.php\1/gi, "action=$1/email.php$1")
  return s
}

function extractTitle(rawHtml) {
  const m = rawHtml.match(/<title>([^<]*)<\/title>/i)
  const t = m ? m[1].trim() : ""
  if (!t || t.includes("<!DOCTYPE") || t.length > 120) return "Yi YUVA REC"
  return t
}

function prepareBodyChromeStrip(rawHtml, portfolioItems, extraEventPages, htmlFileToRoute) {
  const root = parse(rawHtml)
  const body = root.querySelector("body")
  if (!body) {
    return rewriteLinks(rawHtml, portfolioItems, extraEventPages, htmlFileToRoute)
  }
  for (const sel of [
    "header.theme-header",
    ".offcanvas-panel",
    "footer.footer-area",
    "footer.page-footer",
    ".back-to-top",
  ]) {
    body.querySelectorAll(sel).forEach((el) => el.remove())
  }
  body.querySelectorAll("script").forEach((el) => el.remove())
  return rewriteLinks(body.innerHTML, portfolioItems, extraEventPages, htmlFileToRoute)
}

function prepareFullDocument(rawHtml, portfolioItems, extraEventPages, htmlFileToRoute) {
  let s = rewriteLinks(rawHtml, portfolioItems, extraEventPages, htmlFileToRoute)
  if (!/<base\s/i.test(s)) {
    s = s.replace(/<head([^>]*)>/i, '<head$1><base href="/">')
  }
  return s
}

async function main() {
  const siteDir = path.join(__dirname, "../public/site")
  const outDir = path.join(__dirname, "../src/generated")

  const { portfolioItems } = await import(
    pathToFileURL(path.join(__dirname, "../src/data/portfolioItems.js")).href
  )
  const { extraEventPages } = await import(
    pathToFileURL(path.join(__dirname, "../src/data/extraEventPages.js")).href
  )
  const { htmlFileToRoute } = await import(
    pathToFileURL(path.join(__dirname, "../src/data/routeMap.js")).href
  )

  const files = fs.readdirSync(siteDir).filter((f) => f.endsWith(".html"))
  if (files.length === 0) {
    console.error(
      "build-legacy-content: no .html under public/site — skip (keeping src/generated)"
    )
    return
  }
  const titles = {}
  const bodies = {}
  const fullDocs = {}

  for (const f of files) {
    if (SKIP_FILES.has(f)) continue
    const raw = fs.readFileSync(path.join(siteDir, f), "utf8")
    titles[f] = extractTitle(raw)
    if (FULL_DOCUMENT_FILES.has(f)) {
      fullDocs[f] = prepareFullDocument(raw, portfolioItems, extraEventPages, htmlFileToRoute)
    } else {
      bodies[f] = prepareBodyChromeStrip(raw, portfolioItems, extraEventPages, htmlFileToRoute)
    }
  }

  fs.mkdirSync(outDir, { recursive: true })
  fs.writeFileSync(
    path.join(outDir, "legacyContent.js"),
    `// Auto-generated by web/scripts/build-legacy-content.mjs — do not edit\nexport const legacyPageTitles = ${JSON.stringify(titles, null, 2)};\nexport const legacyPageBodies = ${JSON.stringify(bodies, null, 2)};\n`
  )
  fs.writeFileSync(
    path.join(outDir, "legacyFullDocuments.js"),
    `// Auto-generated by web/scripts/build-legacy-content.mjs — do not edit\nexport const legacyFullDocuments = ${JSON.stringify(fullDocs, null, 2)};\n`
  )
  console.error(
    "wrote legacyContent + legacyFullDocuments; bodies:",
    Object.keys(bodies).length,
    "full:",
    Object.keys(fullDocs).length
  )
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
