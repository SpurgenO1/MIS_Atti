import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const portfolioSource = path.join(__dirname, "source", "Initiatives.html");
const html = fs.readFileSync(portfolioSource, "utf8");
const blocks = html.split("portfolio-column");
const items = [];

for (const b of blocks.slice(1)) {
  const catMatch = b.match(/^\s+([a-z0-9\-\s.]+)/);
  const cats = catMatch
    ? catMatch[1].trim().split(/\s+/).filter((c) => c.startsWith("cat-"))
    : [];
  const imgM = b.match(/<img src="([^"]+)"/);
  const vidM = b.match(/<source src="([^"]+)"[^>]*type="video\/mp4"/i);
  const hrefM = b.match(/href="(Event[^"]+\.html)"/);
  let titleM = b.match(/<h3 class="title"><a[^>]*>([^<]*)<\/a><\/h3>/);
  let title = titleM ? titleM[1].trim() : null;
  if (!title) {
    const t2 = b.match(/<h3 class="title"><a[^>]*><\/a>([^<]+)<\/h3>/);
    title = t2 ? t2[1].trim() : null;
  }
  const dateM = b.match(/class="cat-link">([^<]*)</);
  const image = imgM
    ? imgM[1].replace(/\\/g, "/")
    : vidM
      ? vidM[1].replace(/\\/g, "/")
      : null;
  if (hrefM && title && image) {
    items.push({
      file: hrefM[1],
      title,
      date: dateM ? dateM[1].trim() : "",
      image,
      mediaType: vidM && !imgM ? "video" : "image",
      categories: cats,
    });
  }
}

function slugFromFile(file) {
  const base = file.replace(/\.html$/i, "").replace(/^Event - /, "").replace(/^Event-/, "");
  return base
    .toLowerCase()
    .replace(/\s+/g, "-")
    .replace(/[^a-z0-9-]/g, "")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}

const withSlugs = items.map((item) => ({
  ...item,
  slug: slugFromFile(item.file),
}));

const out = `// Auto-generated by scripts/extract-portfolio.mjs — source: scripts/source/Initiatives.html
export const portfolioItems = ${JSON.stringify(withSlugs, null, 2)};
`;
fs.writeFileSync(path.join(__dirname, "..", "web", "src", "data", "portfolioItems.js"), out);
console.error("wrote web/src/data/portfolioItems.js count", withSlugs.length);
